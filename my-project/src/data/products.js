// Helper function to get Ready To Wear products dynamically
const getReadyToWearProducts = () => {
  try {
    const exclusivePretImages = import.meta.glob('../img/Ready To Wear/*.webp', { eager: true });
    const coordsImages = import.meta.glob('../img/co-codr/*.webp', { eager: true });
    const everydayImages = import.meta.glob('../img/EVERYDAY ESSENTIALS/*.webp', { eager: true });
    const luxuryImages = import.meta.glob('../img/LUXURY PRET/*.webp', { eager: true });
    const weddingImages = import.meta.glob('../img/WEDDING COLLECTION/*.webp', { eager: true });
    const bottomImages = import.meta.glob('../img/Bottom/*.webp', { eager: true });

    const getImagesFromGlob = (globObj) => {
      return Object.values(globObj).map(module => module.default);
    };

    const createProductsWithCategory = (images, category, basePrice) => {
      return images.map((img, idx) => ({
        id: `${category}-${idx}`,
        name: `${category} Item ${idx + 1}`,
        image: img,
        price: `Rs. ${basePrice + idx * 1000}`,
        category: category,
        type: category,
        collection: 'ready-to-wear',
        fabric: 'COTTON',
        detail: 'PRINTED',
        designCode: `RTW-${category.toUpperCase()}-${idx}`,
        workDetails: 'Premium quality ready to wear',
        color: 'MULTI'
      }));
    };

    const exclusivePretData = createProductsWithCategory(getImagesFromGlob(exclusivePretImages), 'exclusive-pret', 12500);
    const coordsData = createProductsWithCategory(getImagesFromGlob(coordsImages), 'coords', 5200);
    const everydayData = createProductsWithCategory(getImagesFromGlob(everydayImages), 'everyday', 3200);
    const luxuryData = createProductsWithCategory(getImagesFromGlob(luxuryImages), 'luxury', 18500);
    const weddingData = createProductsWithCategory(getImagesFromGlob(weddingImages), 'wedding', 45000);
    const bottomsData = createProductsWithCategory(getImagesFromGlob(bottomImages), 'bottoms', 2500);

    return [
      ...exclusivePretData,
      ...coordsData,
      ...everydayData,
      ...luxuryData,
      ...weddingData,
      ...bottomsData
    ];
  } catch (error) {
    console.error('Error loading Ready To Wear products:', error);
    return [];
  }
};

// Cached products
let readyToWearCache = null;

// Get product by ID across all collections
export const getProductById = (id) => {
  if (id.startsWith('unstitched-')) {
    return unstitchedProducts.find(p => p.id === id);
  }
  
  // For Ready To Wear products
  if (!readyToWearCache) {
    readyToWearCache = getReadyToWearProducts();
  }
  
  return readyToWearCache.find(p => p.id === id) || null;
};

// Get all products from a collection type
export const getProductsByCollection = (collection) => {
  if (collection === 'unstitched') {
    return unstitchedProducts;
  }
  
  if (collection === 'ready-to-wear') {
    if (!readyToWearCache) {
      readyToWearCache = getReadyToWearProducts();
    }
    return readyToWearCache;
  }
  
  return [];
};
